import type { Analysis, Status, VersionSummary } from '../api'
import { VersionPicker } from './VersionPicker'

export interface AnalysisState {
  loading: boolean
  error: string | null
  result: Analysis | null
}

interface AiReviewTabProps {
  versions: VersionSummary[]
  from: number
  to: number
  ai: Status['ai'] | null
  analysis: AnalysisState | undefined
  onChange: (from: number, to: number) => void
  onAnalyze: () => void
}

export function AiReviewTab({ versions, from, to, ai, analysis, onChange, onAnalyze }: AiReviewTabProps) {
  if (versions.length < 2) {
    return <div className="empty">AI review needs two versions to compare.</div>
  }

  const result = analysis?.result

  return (
    <div>
      <div className="toolbar">
        <VersionPicker versions={versions} from={from} to={to} onChange={onChange} />
        <div className="spacer" />
        <button className="ai" onClick={onAnalyze} disabled={!ai?.configured || analysis?.loading || from === to}>
          {analysis?.loading ? 'Analyzing…' : result ? 'Analyze again' : 'Analyze'}
        </button>
      </div>

      {ai && !ai.configured && (
        <div className="message warn">
          AI analysis is not configured. Set <code>Ai:ApiKey</code> (or <code>OPENAI_API_KEY</code>) for the API and
          restart it. Everything else keeps working without it.
        </div>
      )}
      {ai?.configured && (
        <p className="muted" style={{ marginTop: 0 }}>
          Analyze sends the definitions of version {from} and version {to} to <strong>{ai.endpointHost}</strong> (
          {ai.model}). No table data, credentials or connection details are sent, and the AI cannot run SQL.
        </p>
      )}

      {analysis?.error && <div className="message error">AI analysis failed: {analysis.error}</div>}
      {analysis?.loading && <div className="empty">Waiting for {ai?.model ?? 'the model'}…</div>}

      {result && !analysis?.loading && (
        <>
          {result.embeddedInstructionsDetected && (
            <div className="message warn">
              The routine definition contains text that tries to instruct an AI. It was treated as data and ignored.
            </div>
          )}

          <div className="card">
            <div className="toolbar" style={{ marginBottom: 6 }}>
              <h3 style={{ margin: 0 }}>
                Summary · v{result.fromVersion} → v{result.toVersion}
              </h3>
              <div className="spacer" />
              <span className={`badge risk ${result.riskLevel}`}>Risk: {result.riskLevel}</span>
            </div>
            <p className="summary">{result.summary}</p>
          </div>

          <List title="Changes" items={result.changes} />
          <List title="Potential risks" items={result.risks} empty="No risks identified." />
          <List title="Recommendations" items={result.recommendations} />

          <p className="muted" style={{ fontSize: 12 }}>
            Generated by {result.model} via {result.sentTo}. AI output can be wrong; verify before acting on it.
          </p>
        </>
      )}
    </div>
  )
}

function List({ title, items, empty }: { title: string; items: string[]; empty?: string }) {
  if (items.length === 0 && !empty) return null
  return (
    <div className="card">
      <h3>{title}</h3>
      {items.length === 0 ? (
        <span className="muted">{empty}</span>
      ) : (
        <ul>
          {items.map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ul>
      )}
    </div>
  )
}
